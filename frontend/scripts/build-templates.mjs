// Compiles the MJML master designs and writes them where each consumer needs them:
//   supabase/seed/templates.sql        immutable template_versions rows (bump VERSION to publish)
//   src/generated/templates.json       previews and demo mode
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import mjml2html from 'mjml';
import { DESIGNS } from '../templates/designs.mjs';

const VERSION = 1;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const compiled = DESIGNS.map((design) => {
  const { html, errors } = mjml2html(design.mjml, { validationLevel: 'soft', minify: false, keepComments: false });
  const real = errors.filter((e) => !/\[\[/.test(e.formattedMessage ?? e.message ?? ''));
  if (real.length) throw new Error(`${design.key}: ${real.map((e) => e.formattedMessage).join('\n')}`);
  return { ...design, html };
});

const dollar = (text) => `$tpl$${text}$tpl$`;
const sql = [
  '-- Generated by scripts/build-templates.mjs. Do not edit by hand.',
  ...compiled.map((d) =>
    `insert into template_versions (template_key, version, mjml_source, compiled_html, labels, is_current)
values ('${d.key}', ${VERSION}, ${dollar(d.mjml)}, ${dollar(d.html)}, ${dollar(JSON.stringify(d.labels))}::jsonb, true)
on conflict (template_key, version) do nothing;`),
].join('\n\n');
fs.mkdirSync(path.join(root, 'supabase/seed'), { recursive: true });
fs.writeFileSync(path.join(root, 'supabase/seed/templates.sql'), sql + '\n');

const generated = path.join(root, 'src/generated');
fs.mkdirSync(generated, { recursive: true });
fs.writeFileSync(
  path.join(generated, 'templates.json'),
  JSON.stringify(compiled.map((d) => ({ key: d.key, name: d.name, position: d.position, version: VERSION, html: d.html, labels: d.labels })), null, 1),
);
console.log(`Compiled ${compiled.length} templates`);
